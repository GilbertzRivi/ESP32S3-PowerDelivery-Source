# Ground offset boost (GPIO6): 47R under the TX emitters and 1k under the Vref divider, each shorted by a BC547.
from common import *
with schemdraw.Drawing(file='boost.svg', show=False) as d:
    d.config(bgcolor='white')
    # TX side
    E = Point((0, 0))
    d += elm.Dot().at(E).label('E_CC', loc='left')
    d += elm.Line().at(E).up().length(1.2).label('emitters of both\nTX BC547 (CC1, CC2)', loc='end')
    d += elm.Resistor().at(E).down().length(2.6).label('47R', loc='top')
    G1 = Point((0, -2.6))
    d += elm.Ground().at(G1).label('GND_CC', loc='bottom', ofst=0.15)
    d += (q1 := elm.BjtNpn(circle=True).theta(180).flip().anchor('collector').at((2.0, -0.6)).label('BC547', loc='left'))
    W(d, E, (q1.collector.x, 0)); W(d, (q1.collector.x, 0), q1.collector)
    W(d, q1.emitter, (q1.emitter.x, G1.y)); W(d, (q1.emitter.x, G1.y), G1)
    d += elm.Resistor().at(q1.base).right().length(2.0).label('1k')
    n1 = Point((q1.base.x + 2.0, q1.base.y))
    d += elm.Dot().at(n1)
    # Vref side
    xv = 9.0
    d += elm.Vdd().at((xv, 1.4)).label('3V3')
    d += elm.Resistor().at((xv, 1.4)).down().length(2.0).label('10k', loc='top')
    V = Point((xv, -0.6))
    d += elm.Dot().at(V)
    d += elm.Line().at(V).right().length(1.6)
    d += (vd := elm.Dot())
    d += elm.Capacitor().at(vd.center).down().length(1.6).label('100n', loc='bottom')
    d += elm.Ground().label('GND_CC', loc='bottom', ofst=0.15)
    d += elm.Line().at(vd.center).right().length(1.2)
    lab(d, (vd.center.x + 1.2, V.y), 'Vref\nto IN- of\nboth LM311', loc='right')
    d += elm.Resistor().at(V).down().length(2.0).label('2k', loc='top')
    X = Point((xv, -2.6))
    d += elm.Dot().at(X)
    d += elm.Resistor().at(X).down().length(2.0).label('1k', loc='top')
    G2 = Point((xv, -4.6))
    d += elm.Ground().at(G2).label('GND_CC', loc='bottom', ofst=0.15)
    d += (q2 := elm.BjtNpn(circle=True).theta(0).anchor('collector').at((xv - 1.4, -3.0)).label('BC547', loc='right', ofst=(-1.9, 0.9)))
    W(d, q2.collector, (q2.collector.x, X.y)); W(d, (q2.collector.x, X.y), X)
    W(d, q2.emitter, (q2.emitter.x, G2.y)); W(d, (q2.emitter.x, G2.y), G2)
    n2 = Point((n1.x, q2.base.y))
    d += elm.Resistor().at(n2).right().to(q2.base).label('1k')
    d += elm.Dot().at(n2)
    W(d, n1, n2)
    d += elm.Resistor().at(n1).up().length(1.8).label('10k')
    d += elm.Vdd().label('3V3')
    d += elm.Line().at(n2).down().length(1.2).label('GPIO6\nhigh = normal\nlow = boost', loc='end')
